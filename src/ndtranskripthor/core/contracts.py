"""Structural boundaries; no dependency on Tk, a concrete model or SQLite.

Adapters implement these protocols without inheritance. IPC event names and
payloads remain the existing versioned asr_process protocol, not UI text.
"""
from pathlib import Path
from typing import Any, Protocol


class EventSink(Protocol):
    def put(self, event: tuple[str, Any]) -> None: ...


class Transcriber(Protocol):
    def transcribe(self, audio: Any, **options: Any) -> tuple[Any, Any]: ...


class ProfileStore(Protocol):
    folder: Path
    warning: str
    def settings(self, languages: Any, models: Any) -> dict: ...
    def save_settings(self, values: dict) -> None: ...
    def queue(self) -> list[dict]: ...
    def save_queue(self, items: list[dict]) -> None: ...


class Playback(Protocol):
    audio: Any
    position: int
    rate: float
    device: Any
    @property
    def playing(self) -> bool: ...
    def configure(self, rate: float, device: Any) -> None: ...
    def poll_error(self) -> str | None: ...
    def load(self, source: Any, folder: Any = None) -> float: ...
    def seek(self, seconds: float, resume: bool | None = None) -> None: ...
    def play(self, start: float | None = None, end: float | None = None) -> None: ...
    def pause(self) -> None: ...
    def close(self) -> None: ...


class ExportProject(Protocol):
    """Immutable revision reads and atomic export-state publication, no SQL."""
    folder: Path
    def segments(self, view: str, revision: int | None = None) -> list[dict]: ...
    def get(self, key: str, default: Any = None) -> Any: ...
    def subtitle_options(self) -> Any: ...
    def record_export(self, request: dict) -> None: ...
